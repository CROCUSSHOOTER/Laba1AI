# ЗАДАНИЕ 5. Поиск максимального значения
# ==============================================================================
print("=== ЗАДАНИЕ 5 ===")
scores = [67, 82, 45, 91, 76, 88, 54]
maximum = scores[0]

print(f"{'score':<7} | {'maximum до':<10} | {'score > max':<11} | {'maximum после':<13}")
print("-" * 50)

for score in scores:
    max_before = maximum
    is_greater = score > maximum
    if is_greater:
        maximum = score
    print(f"{score:<7} | {max_before:<10} | {str(is_greater):<11} | {maximum:<13}")
print()


