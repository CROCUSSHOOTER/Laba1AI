# ЗАДАНИЕ 4. Накопление состояния в цикле
# ==============================================================================
print("=== ЗАДАНИЕ 4 ===")
numbers = [12, 5, 8, 3, 21, 0, 14, -7]

sum_all = 0
sum_pos = 0
count_pos = 0
count_neg = 0
count_zero = 0

print("Таблица изменения sum_all на каждой итерации:")
for i, num in enumerate(numbers, 1):
    sum_all += num  # Накопление суммы всех чисел
    
    if num > 0:
        sum_pos += num
        count_pos += 1
    elif num < 0:
        count_neg += 1
    else:
        count_zero += 1
        
    print(f"Итерация {i} | Число: {num:>2} | sum_all: {sum_all}")

print(f"\nСумма всех чисел: {sum_all}")
print(f"Сумма положительных: {sum_pos}")
print(f"Количество положительных: {count_pos}")
print(f"Количество отрицательных: {count_neg}")
print(f"Количество нулей: {count_zero}\n")


