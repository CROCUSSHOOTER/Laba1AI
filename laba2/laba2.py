# ИНДИВИДУАЛЬНОЕ ЗАДАНИЕ №1. Банковский счет
# ==============================================================================
print("=== ИНДИВИДУАЛЬНОЕ ЗАДАНИЕ №1 ===")

balance = 100000.0  # Начальное состояние счета
withdraw_requests = [30000, 80000, 50000]  # Симуляция операций снятия

print(f"Начальный баланс: {balance:.2f} тг.\n")

for amount in withdraw_requests:
    print(f"Запрос на снятие: {amount:.2f} тг.")
    
    if amount <= 0:
        print("Ошибка: сумма должна быть больше нуля.\n")
    elif amount <= balance:
        balance -= amount  # Явное изменение состояния
        print(f"Успешно! Снято: {amount:.2f} тг.")
        print(f"Остаток на балансе: {balance:.2f} тг.\n")
    else:
        print(f"Ошибка: Недостаточно средств! Баланс: {balance:.2f} тг.\n")

print(f"Итоговое состояние баланса: {balance:.2f} тг.")
